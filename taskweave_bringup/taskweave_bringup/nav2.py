"""Nav2 for a taskweave robot: the parameters file and the nodes.

The robot's own values come from its pack, as taskweave maps them everywhere (``taskweave_skills.nav2.nav2_parameters``,
the same translation the HMI uses live): footprint, padding and inflation from ``navigation.yaml``, driving limits and
the MPPI motion model from ``navigation.yaml`` and ``base.type``, the base frame, ``cmd_vel`` and odometry topics from
the profile's ``base``. The rest (MPPI, critics, costmap layers) is tuning: the packaged ``config/nav2_params.yaml``,
or a robot pack's / the cell pack's ``robots/<robot>/nav2_params.yaml`` (see :func:`robot_files.layered_file`).
The map (a Nav2 map yaml) and the transform that attaches the map frame belong to the application.
"""

from __future__ import annotations

import copy
import tempfile
from pathlib import Path

import yaml
from ament_index_python.packages import PackageNotFoundError, get_package_share_directory

from taskweave_skills.nav2 import nav2_parameters

from . import robot_files

PARAMS_NAME = 'nav2_params.yaml'
NAV_NODES = ['map_server', 'planner_server', 'controller_server', 'behavior_server', 'bt_navigator']


def default_template() -> Path:
    """The packaged tuning: share/taskweave_bringup/config when installed, else the source tree's config/."""
    try:
        installed = Path(get_package_share_directory('taskweave_bringup')) / 'config' / PARAMS_NAME
    except PackageNotFoundError:
        installed = None
    source = Path(__file__).resolve().parents[1] / 'config' / PARAMS_NAME
    return installed if installed and installed.is_file() else source


def default_output_dir(robot: str) -> Path:
    return Path(tempfile.gettempdir()) / 'taskweave' / 'nav2' / robot


def set_dotted(params: dict, key: str, value) -> None:
    """params['a']['b'] = value for key 'a.b' (ROS parameter names with dots are nested in a params file)."""
    *path, last = key.split('.')
    for part in path:
        params = params.setdefault(part, {})
    params[last] = value


def set_everywhere(tree, key: str, value) -> None:
    """Every mapping in the tree that has ``key`` gets ``value`` (use_sim_time in each node's section)."""
    if isinstance(tree, dict):
        if key in tree:
            tree[key] = value
        for child in tree.values():
            set_everywhere(child, key, value)


def build_parameters(template: dict, navigation: dict, base: dict, map_yaml: str, use_sim_time: bool) -> dict:
    """The Nav2 parameters: the template with the robot's values written in (a new dict; the template is kept)."""
    tuning = copy.deepcopy(template)
    values = nav2_parameters(navigation, base)
    for name in ('local_costmap', 'global_costmap'):
        costmap = tuning[name][name]['ros__parameters']
        costmap['robot_base_frame'] = base['frame']
        for key, value in values['costmap'].items():
            set_dotted(costmap, key, value)
    controller = tuning['controller_server']['ros__parameters']
    for key, value in values['controller'].items():
        set_dotted(controller, key, value)
    controller['FollowPath']['motion_model'] = values['motion_model']
    tuning['map_server']['ros__parameters']['yaml_filename'] = str(map_yaml)
    tuning['bt_navigator']['ros__parameters'].update(odom_topic=base['odom'], robot_base_frame=base['frame'])
    tuning['behavior_server']['ros__parameters']['robot_base_frame'] = base['frame']
    set_everywhere(tuning, 'use_sim_time', use_sim_time)
    return tuning


def write_parameters(config_dir: str, robot: str, map_yaml: str, output_dir: str = '', use_sim_time: bool = True,
                     template: str = '') -> tuple[Path, dict]:
    """Generate ``<output_dir>/nav2_params.yaml`` for the robot; returns (path, base profile)."""
    store = robot_files.open_store(config_dir)
    base = robot_files.base_profile(store, robot)
    data = robot_files.layered_file(store, robot, PARAMS_NAME, default_template(), template)
    params = build_parameters(data, robot_files.navigation(store, robot), base, map_yaml, use_sim_time)
    out = Path(output_dir) if output_dir else default_output_dir(robot)
    out.mkdir(parents=True, exist_ok=True)
    path = out / PARAMS_NAME
    source = robot_files.source_of(store, robot, PARAMS_NAME, default_template(), template)
    with open(path, 'w', encoding='utf-8') as handle:
        handle.write(f'# generated by taskweave_nav2.launch.py from {source} and the robot pack\n')
        yaml.safe_dump(params, handle, sort_keys=False)
    return path, base


def nav2_nodes(config_dir: str, robot: str, map_yaml: str, output_dir: str = '', use_sim_time: bool = True,
               template: str = '', map_topic: str = '/map') -> list:
    """Map server (serving the map on ``map_topic``), planner, controller (MPPI), behaviors, BT navigator and the
    lifecycle manager that starts them."""
    from launch_ros.actions import Node

    if not map_yaml:
        raise ValueError('nav2 needs a map: pass map:=<path of a Nav2 map yaml> (the application makes it)')
    params, base = write_parameters(config_dir, robot, map_yaml, output_dir, use_sim_time, template)
    common = {'use_sim_time': use_sim_time}
    remap_cmd = [('cmd_vel', base['cmd_vel'])]
    return [
        Node(package='nav2_map_server', executable='map_server', name='map_server', output='screen',
             parameters=[str(params), common], remappings=[('map', map_topic)]),
        Node(package='nav2_planner', executable='planner_server', name='planner_server', output='screen',
             parameters=[str(params), common]),
        Node(package='nav2_controller', executable='controller_server', name='controller_server', output='screen',
             parameters=[str(params), common], remappings=remap_cmd),
        Node(package='nav2_behaviors', executable='behavior_server', name='behavior_server', output='screen',
             parameters=[str(params), common], remappings=remap_cmd),
        Node(package='nav2_bt_navigator', executable='bt_navigator', name='bt_navigator', output='screen',
             parameters=[str(params), common]),
        Node(package='nav2_lifecycle_manager', executable='lifecycle_manager', name='lifecycle_manager_navigation',
             output='screen', parameters=[common, {'autostart': True, 'node_names': NAV_NODES,
                                                    'bond_timeout': 10.0}]),
    ]
