"""Robot files come from taskweave's search path (cell pack, then robot packs), and the Nav2 tuning is layered:
packaged default, a robot pack's nav2_params.yaml, the cell pack's (whole file or keyed override), a launch argument."""

import pytest
import yaml

pytest.importorskip('launch_ros')
pytest.importorskip('taskweave_skills')

from conftest import write  # noqa: E402

from taskweave_bringup import nav2, robot_files  # noqa: E402

FOLLOW = ('controller_server', 'ros__parameters', 'FollowPath')


def follow_path(params: dict) -> dict:
    for key in FOLLOW:
        params = params[key]
    return params


def default_template() -> dict:
    return yaml.safe_load(nav2.default_template().read_text(encoding='utf-8'))


def generate(cell, tmp_path, **kwargs):
    path, base = nav2.write_parameters(str(cell), 'test_bot', '/maps/cell.yaml', str(tmp_path / 'out'), **kwargs)
    return yaml.safe_load(path.read_text(encoding='utf-8')), path, base


def pack_file(cell, **follow):
    """A robots-pack nav2_params.yaml: the default with FollowPath values changed."""
    template = default_template()
    follow_path(template).update(follow)
    return write(cell.parent / 'packs' / 'test_bot' / 'nav2_params.yaml', yaml.safe_dump(template))


def test_robot_values_are_written(cell, tmp_path):
    params, path, base = generate(cell, tmp_path)
    assert base['frame'] == 'test_base'
    controller = follow_path(params)
    assert controller['vx_max'] == 1.0 and controller['vx_min'] == -0.4 and controller['wz_max'] == 1.0
    assert controller['vy_max'] == 0.0 and controller['motion_model'] == 'DiffDrive'
    assert controller['PreferForwardCritic']['cost_weight'] == 2.0
    for costmap in ('local_costmap', 'global_costmap'):
        section = params[costmap][costmap]['ros__parameters']
        assert section['robot_base_frame'] == 'test_base'
        assert section['footprint'] == '[[0.5, 0.3], [0.5, -0.3], [-0.2, -0.3], [-0.2, 0.3]]'
        assert section['footprint_padding'] == 0.05
    assert params['bt_navigator']['ros__parameters']['odom_topic'] == '/test/odom'
    assert params['behavior_server']['ros__parameters']['robot_base_frame'] == 'test_base'
    assert path.read_text(encoding='utf-8').startswith('# generated by taskweave_nav2.launch.py')


def test_use_sim_time_follows_the_argument(cell, tmp_path):
    params, _, _ = generate(cell, tmp_path, use_sim_time=False)
    assert params['bt_navigator']['ros__parameters']['use_sim_time'] is False
    assert params['local_costmap']['local_costmap']['ros__parameters']['use_sim_time'] is False


def test_default_template_is_used_without_overrides(cell, tmp_path):
    params, _, _ = generate(cell, tmp_path)
    assert follow_path(params)['batch_size'] == follow_path(default_template())['batch_size']


def test_robot_pack_file_replaces_the_default(cell, tmp_path):
    pack_file(cell, batch_size=123)
    assert follow_path(generate(cell, tmp_path)[0])['batch_size'] == 123


def test_cell_pack_file_wins_over_the_robot_pack(cell, tmp_path):
    pack_file(cell, batch_size=123)
    template = default_template()
    follow_path(template)['batch_size'] = 77
    write(cell / 'robots' / 'test_bot' / 'nav2_params.yaml', yaml.safe_dump(template))
    assert follow_path(generate(cell, tmp_path)[0])['batch_size'] == 77


def test_keyed_cell_override_over_the_default(cell, tmp_path):
    write(cell / 'robots' / 'test_bot' / 'nav2_params.yaml',
          '~override: keys\ncontroller_server:\n  ros__parameters:\n    FollowPath:\n      batch_size: 55\n')
    follow = follow_path(generate(cell, tmp_path)[0])
    assert follow['batch_size'] == 55
    assert follow['time_steps'] == follow_path(default_template())['time_steps']
    assert follow['vx_max'] == 1.0   # still the robot's value


def test_keyed_cell_override_over_the_robot_pack_file(cell, tmp_path):
    pack_file(cell, batch_size=123, time_steps=40)
    write(cell / 'robots' / 'test_bot' / 'nav2_params.yaml',
          '~override: keys\ncontroller_server:\n  ros__parameters:\n    FollowPath:\n      batch_size: 55\n')
    follow = follow_path(generate(cell, tmp_path)[0])
    assert follow['batch_size'] == 55 and follow['time_steps'] == 40


def test_explicit_file_wins(cell, tmp_path):
    pack_file(cell, batch_size=9)
    explicit = default_template()
    explicit['bt_navigator']['ros__parameters']['bt_loop_duration'] = 3
    explicit = write(tmp_path / 'mine.yaml', yaml.safe_dump(explicit))
    params, path, _ = generate(cell, tmp_path, template=str(explicit))
    assert params['bt_navigator']['ros__parameters']['bt_loop_duration'] == 3
    assert follow_path(params)['batch_size'] == follow_path(default_template())['batch_size']
    assert str(explicit) in path.read_text(encoding='utf-8').splitlines()[0]


def test_robot_files_use_the_store_search_path(cell):
    store = robot_files.open_store(cell)
    assert robot_files.moveit_folder(store, 'test_bot') == cell.parent / 'packs' / 'test_bot' / 'moveit'
    write(cell / 'robots' / 'test_bot' / 'moveit' / 'robot.urdf', '<robot name="cell"/>')   # a cell copy wins whole
    store = robot_files.open_store(cell)
    assert robot_files.moveit_folder(store, 'test_bot') == cell / 'robots' / 'test_bot' / 'moveit'
    write(cell / 'robots' / 'test_bot' / 'navigation.yaml', '~override: keys\npadding: 0.2\n')
    navigation = robot_files.navigation(robot_files.open_store(cell), 'test_bot')
    assert navigation['padding'] == 0.2 and navigation['envelope']['front'] == 0.5


def test_default_output_dir_is_per_robot():
    assert nav2.default_output_dir('a') != nav2.default_output_dir('b')
