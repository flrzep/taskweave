#!/usr/bin/env python3
# ruff: noqa: E501  (INTRO holds Markdown table rows)
"""Generate docs/skills.md, the skill reference, from the skill classes.

    python3 tools/gen_skills_doc.py            # write docs/skills.md
    python3 tools/gen_skills_doc.py --check    # exit 1 if docs/skills.md is out of date (the test does the same)
    python3 tools/gen_skills_doc.py --stdout   # print instead of writing

It needs the ROS 2 environment sourced (the skill modules import rclpy message packages) and ``taskweave_core`` and
``taskweave_skills`` on the PYTHONPATH (or installed), but no running ROS graph and no robot: it imports the classes and
reads their attributes (``name``, ``description``, ``args_schema``, ``needs``, ``achieves``, ``default_timeout_s``)
without constructing them. The ``requires`` of a skill come from its skill yaml in the example cell
(docs/examples/skills/*.yaml, the files a cell pack starts from); the example steps come from
docs/examples/skill_steps.yaml. Both are data: change them, then run this.
"""

from __future__ import annotations

import argparse
import importlib
import sys
import textwrap
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
OUTPUT = REPO / 'docs' / 'skills.md'
EXAMPLES = REPO / 'docs' / 'examples' / 'skill_steps.yaml'
SKILL_FILES = REPO / 'docs' / 'examples' / 'skills'
SKILL_PACKAGE = 'taskweave_skills'

INTRO = """\
# Skill reference

> Generated by `tools/gen_skills_doc.py` from the skill classes. Do not edit by hand: change the class (description,
> `args_schema`, `needs`, `achieves`) or `docs/examples/skill_steps.yaml`, then run
> `python3 tools/gen_skills_doc.py`. A test (`taskweave_skills/test/test_skills_doc.py`) fails when this file is out of
> date.

A skill executes one step of a mission: `{instruction, skill, args}`. The arguments are checked against the skill's JSON
schema (tables below) before anything moves; values with `{placeholders}` are checked when the step starts. Arguments
that name a target (a base, hand, object or joint target) are checked against the config too.
How to write missions: [missions.md](missions.md). How a skill is configured and which robots can run it:
[configuration.md](configuration.md) (skill implementations, skill parameters).

Every step can also set the decision rules `timeout_s`, `retries`, `on_failure`, `replan_from`, `max_replans`
(see [missions.md](missions.md)); they are not skill arguments.

## Shared argument types

| Type | Meaning |
|---|---|
| `hands` | Which hands act: a hand name from the robot profile (`grippers`), a list of names, or a rule word: `auto` (the hands the target defines or, for a held object, the hands that hold it), `any_one` (one free hand that can take the target), `all` (every hand). Each skill accepts the rule words listed in its table. |
| `vec3` | `[x, y, z]`, three numbers. |
| `point` | A string naming something in the config. The point kind is shown in the description: `target` (`<name>` for a cell, base or joint target, `<instance>/<name>` for a target of a placed object; the kinds a field takes are named in its description, see [targets.md](targets.md)), `joint_group`, `held_object`. |
| `motion` | Options of the motion, see the `motion` table of `move`. Defaults come from the skill yaml (`skills/move/<part>.yaml`), then the robot (`skill_overrides.yaml`), then the target's own data (a hand target's `approach_m`, `elbow`), then the step. |

`RunSkill` outcomes: `SUCCEEDED`, `FAILED` (ran but missed the goal), `TIMEOUT`, `CANCELED`, `REJECTED` (invalid
arguments or unmet preconditions; nothing moved).

The **global speed override** (1 to 100 %, see the README) scales every skill's speed and its timeout: a step at 10 %
gets ten times its nominal `timeout_s`. A step's own `motion.speed` is a fraction of the skill's standard speed and the
override applies on top.
"""


def load_skills() -> list[type]:
    """Every shipped skill class (taskweave_skills.shipped_skills: imported, never instantiated)."""
    return importlib.import_module(SKILL_PACKAGE).shipped_skills()


def examples() -> dict:
    return yaml.safe_load(EXAMPLES.read_text(encoding='utf-8')) or {}


def ordered(skills: list[type], order: list[str]) -> list[type]:
    rank = {name: index for index, name in enumerate(order)}
    return sorted(skills, key=lambda skill: (rank.get(skill.name, len(rank)), skill.name))


def templates() -> dict[str, dict]:
    """skill name -> parsed skill yaml of the example cell (implementations, parameters), where there is one."""
    return {path.stem: yaml.safe_load(path.read_text(encoding='utf-8')) for path in sorted(SKILL_FILES.glob('*.yaml'))}


def parts(name: str) -> dict[str, dict]:
    """part name -> parsed yaml of ``skills/<name>/<part>.yaml`` in the example cell (a skill that hands its work to
    modules, like ``move``)."""
    folder = SKILL_FILES / name
    return {path.stem: yaml.safe_load(path.read_text(encoding='utf-8')) for path in sorted(folder.glob('*.yaml'))}


# ---- schema rendering -----------------------------------------------------------------------------------------
def type_of(schema: dict) -> str:
    if schema.get('x-taskweave-widget') == 'hands':
        return 'hands'
    if schema.get('x-taskweave-widget') == 'vec3':
        return 'vec3'
    if 'enum' in schema:
        return 'one of ' + ', '.join(f'`{value}`' for value in schema['enum'])
    if 'oneOf' in schema:
        return 'one of the variants below'
    kind = schema.get('type', 'any')
    if isinstance(kind, list):      # e.g. [number, 'null']: a number or empty
        return ' or '.join(str(k) for k in kind)
    if kind == 'array':
        item = schema.get('items', {})
        return f'list of {type_of(item)}' if item else 'list'
    if kind == 'object':
        extra = schema.get('additionalProperties')
        if 'properties' not in schema and isinstance(extra, dict) and extra.get('type'):
            return f'map name to {extra["type"]}'
        return 'object' if 'properties' not in schema else 'object (table below)'
    if 'anyOf' in schema:
        return ' or '.join(type_of(item) for item in schema['anyOf'])
    return str(kind)


def constraints(schema: dict) -> list[str]:
    out = []
    for key, text in (('minimum', 'min {}'), ('exclusiveMinimum', 'above {}'), ('maximum', 'max {}')):
        if key in schema:
            out.append(text.format(schema[key]))
    if schema.get('uniqueItems') and schema.get('type') == 'array':
        out.append('no repeats')
    return out


def description_of(name: str, schema: dict) -> str:
    text = ' '.join(str(schema.get('description', '')).split())
    if not text and schema.get('properties'):
        text = 'Options, see the table below.'
    notes = constraints(schema)
    if schema.get('x-taskweave-point'):
        notes.append(f'point kind `{schema["x-taskweave-point"]}`')
    if schema.get('x-taskweave-widget') == 'hands':
        # the rule words sit in an enum branch; a class-level hands field (move's `hand`) may have none
        rules = [rule for item in schema.get('anyOf', []) for rule in item.get('enum', [])]
        if any(rule in HAND_WORDS for rule in rules):
            notes.append('rule words: ' + ', '.join(f'`{rule}`' for rule in rules if rule in HAND_WORDS))
    show_if = schema.get('x-taskweave-show-if')
    if show_if:
        notes.append('only with ' + ' and '.join(f'`{key}` = ' + ' / '.join(f'`{v}`' for v in values)
                                                  for key, values in show_if.items()))
    if text and not text.endswith('.'):
        text += '.'
    return text + (' ' if text and notes else '') + (f'({"; ".join(notes)})' if notes else '')


HAND_WORDS = ('auto', 'any_one', 'all')


def cell(text) -> str:
    """A table cell: pipes escaped, angle brackets outside code spans shown literally (not read as HTML tags)."""
    if text in (None, ''):
        return '-'
    parts = str(text).split('`')
    parts[::2] = [part.replace('<', '&lt;').replace('>', '&gt;') for part in parts[::2]]
    return '`'.join(parts).replace('|', '\\|')


def table(properties: dict, required: set[str], group_note: str | None = None) -> list[str]:
    lines = ['| Argument | Type | Required | Default | Unit | Description |', '|---|---|---|---|---|---|']
    for name, schema in properties.items():
        default = schema.get('default')
        lines.append('| `{}` | {} | {} | {} | {} | {} |'.format(
            name, cell(type_of(schema)), 'yes' if name in required else 'no',
            '-' if default is None else f'`{default}`', cell(schema.get('x-taskweave-unit')),
            cell(description_of(name, schema))))
    return lines


def nested(name: str, schema: dict, level: int) -> list[str]:
    """Sub-sections for an argument that is itself an object (motion options) or a oneOf of objects (to)."""
    lines: list[str] = []
    heading = '#' * level
    if 'oneOf' in schema:
        lines += [f'{heading} `{name}` variants', '', 'Give exactly one of these forms.', '']
        for variant in schema['oneOf']:
            title = variant.get('title', 'variant')
            lines += [f'**{title}**', '']
            lines += table(variant.get('properties', {}), set(variant.get('required', []))) + ['']
            for sub, sub_schema in variant.get('properties', {}).items():
                lines += nested(f'{name}.{sub}', sub_schema, level + 1)
    elif schema.get('type') == 'object' and schema.get('properties'):
        group = schema.get('x-taskweave-group')
        lines += [f'{heading} `{name}` options', '']
        if group:
            lines += [f'All optional ({group}). Defaults are those of the skill yaml, the robot and the target.', '']
        lines += table(schema['properties'], set(schema.get('required', []))) + ['']
        for sub, sub_schema in schema['properties'].items():
            if sub_schema.get('type') == 'array' and isinstance(sub_schema.get('items'), dict):
                continue
            lines += nested(f'{name}.{sub}', sub_schema, level + 1)
    return lines


def requirement_notes(schema: dict) -> list[str]:
    notes = []
    if 'oneOf' in schema:
        forms = [' + '.join(f'`{key}`' for key in variant.get('required', [])) for variant in schema['oneOf']]
        notes.append('Give exactly one of: ' + ' or '.join(forms) + '.')
        if all(variant.get('title') for variant in schema['oneOf']):
            titled = [f'{variant["title"].lower()} ({" + ".join(f"`{key}`" for key in variant["required"])})'
                      for variant in schema['oneOf']]
            notes.append('The forms: ' + '; '.join(titled) + '.')
    then = schema.get('then', {}).get('required')
    condition = schema.get('if', {}).get('properties', {})
    for key, value in condition.items():
        if then and 'const' in value:
            notes.append(f'`{", ".join(then)}` is required when `{key}` is `{value["const"]}`.')
    return notes


def implementations(template: dict | None, skill: type) -> list[str]:
    if template and template.get('implementations'):
        entries = template['implementations']
        intro = 'Implementation entry of the shipped skill yaml (`implementations:` in `skills/<name>.yaml`):'
    else:
        entries = [{'name': skill.name, 'type': 'script', 'class': f'{skill.__module__}:{skill.__name__}'}]
        intro = ('No `requires` in the minimal `skills/<name>.yaml` below: the skill is served on every robot (a run '
                 'that does not fit the robot is rejected by the skill itself):')
    lines = [intro, '', '```yaml']
    lines += yaml.safe_dump({'implementations': entries}, sort_keys=False, default_flow_style=None,
                            width=120).splitlines()
    return lines + ['```']


def part_lines(name: str) -> list[str]:
    """The modules of a skill that has some: which file configures each, and its implementations."""
    found = parts(name)
    if not found:
        return []
    lines = ['### Parts', '',
             f'`{name}` hands each step to the module that does that kind of motion. Each module is configured in '
             f'`skills/{name}/<part>.yaml` (`implementations` with `requires`, speeds, tolerances) and is served '
             f'or not on its own: a kind whose module has no implementation for the robot is rejected with the '
             f'reasons, the other kinds work.', '', '| Part | File | Implementations (first that fits the robot is served) |',
             '|---|---|---|']
    for part, data in found.items():
        entries = ', '.join(f'`{item["name"]}` (`{item["class"].split(":")[-1]}`'
                            + (f', requires {", ".join(item["requires"].get("capabilities", []))}'
                               if item.get('requires') else '') + ')' for item in data.get('implementations', []))
        lines.append(f'| `{name}.{part}` | `skills/{name}/{part}.yaml` | {entries} |')
    return lines + ['']


def step_yaml(step: dict) -> list[str]:
    body = yaml.safe_dump([step], sort_keys=False, default_flow_style=None, width=110).splitlines()
    return ['```yaml', *body, '```']


def section(skill: type, template: dict | None, steps: list[dict]) -> list[str]:
    schema = skill.args_schema
    lines = [f'## `{skill.name}`', '']
    lines += textwrap.wrap(' '.join(skill.description.split()), 118) + ['']
    lines += [f'- Class: `{skill.__module__}:{skill.__name__}`',
              f'- Default timeout: {skill.default_timeout_s:g} s (sim time when `use_sim_time` is set; `timeout_s` of '
              'the step or mission defaults overrides it)']
    if schema.get('x-taskweave-resources'):
        lines.append('- Uses: ' + ', '.join(f'`{r}`' for r in schema['x-taskweave-resources']))
    if skill.needs:
        lines.append('- Needs: ' + '; '.join(skill.needs))
    if skill.achieves:
        lines.append('- Achieves: ' + '; '.join(skill.achieves))
    lines += ['', '### Implementation and requires', ''] + implementations(template, skill) + ['']
    lines += part_lines(skill.name)
    lines += ['### Arguments', '']
    properties = schema.get('properties', {})
    lines += requirement_notes(schema) + ([''] if requirement_notes(schema) else [])
    lines += table(properties, set(schema.get('required', []))) + ['']
    for name, prop in properties.items():
        lines += nested(name, prop, 3)
    lines += ['### Example', '']
    for step in steps:
        lines += step_yaml(step) + ['']
    return lines


def generate() -> str:
    data = examples()
    skills = ordered(load_skills(), list(data))
    by_name = templates()
    out = [INTRO.rstrip('\n'), '', '| Skill | Purpose |', '|---|---|']
    for skill in skills:
        first = ' '.join(skill.description.split()).split('. ')[0].rstrip('.') + '.'
        out.append(f'| [`{skill.name}`](#{skill.name}) | {first.replace("|", chr(92) + "|")} |')
    out.append('')
    for skill in skills:
        out += section(skill, by_name.get(skill.name), data.get(skill.name, []))
    return '\n'.join(out).rstrip('\n') + '\n'


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='exit 1 if docs/skills.md is out of date')
    parser.add_argument('--stdout', action='store_true', help='print instead of writing')
    options = parser.parse_args(argv)
    text = generate()
    if options.stdout:
        sys.stdout.write(text)
        return 0
    if options.check:
        current = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
        if current != text:
            print(f'{OUTPUT} is out of date: run python3 tools/gen_skills_doc.py', file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print(f'wrote {OUTPUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
